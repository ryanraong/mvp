function buildReview(seed: HotelSeed): ReviewSummary {
  const strengths = seed.tags.map((t) => STRENGTH_PHRASES[t]).filter(Boolean).slice(0, 3);
  const concerns = (seed.concernTags ?? []).map((t) => CONCERN_PHRASES[t]).filter(Boolean).slice(0, 3);
  return {
    hotelId: seed.id,
    strengths,
    concerns,
    isolatedComplaints: seed.isolatedComplaints ?? [],
    unverifiedAnecdotes: seed.unverifiedAnecdotes ?? [],
    recency: seed.recency,
    travelerTypeRelevance: seed.travelerTypeRelevance,
    roomSpecificNotes: seed.roomSpecificNotes,
    avgScore: seed.avgScore,
    reviewCount: seed.reviewCount,
  };
}

function buildRooms(seed: HotelSeed): Room[] {
  const nights = NEIGHBOURHOOD_NIGHTS[seed.neighbourhood];
  return seed.rooms.map((r, idx) => ({
    id: `${seed.id}-room-${idx}`,
    hotelId: seed.id,
    name: r.name,
    sizeSqm: r.sizeSqm,
    bedType: r.bedType,
    occupancy: r.occupancy,
    bathroom: r.bathroom,
    smoking: false,
    view: r.view,
    breakfastIncluded: r.breakfastIncluded,
    cancellation: r.cancellation,
    cancellationDeadline: r.cancellationDeadline,
    nightlyRate: r.pricePerNight,
    totalPriceForStay: r.pricePerNight * nights,
    currency: "SGD",
    priceConfidence: r.priceConfidence,
    priceSource: r.priceSource,
    retrievedAt: RETRIEVED_AT,
    taxesIncluded: r.taxesIncluded,
    prepaymentRequired: r.prepaymentRequired,
  }));
}

function buildHotel(seed: HotelSeed): Hotel {
  const neighbourhood: NeighbourhoodSummary = findNeighbourhood(seed.neighbourhood);
  const toPlaces: Record<string, ReturnType<typeof estimatePlaceTransport>> = {};
  for (const place of SEED_PLACES) {
    toPlaces[place.id] = estimatePlaceTransport(seed.id, seed.neighbourhood, place.id);
  }
  const bathrooms = new Set(seed.rooms.map((r) => r.bathroom));
  return {
    id: seed.id,
    name: seed.name,
    destination: neighbourhood.destination,
    neighbourhood: seed.neighbourhood,
    lat: 0,
    lng: 0,
    priceTier: seed.priceTier,
    sources: seed.sources,
    isUserCandidate: seed.isUserCandidate,
    mixedBathroomWarning: bathrooms.size > 1,
    experienceTags: seed.tags,
    concernTags: seed.concernTags ?? [],
    fromArrivalPoint: estimateAirportTransport(seed.id, seed.neighbourhood),
    toDeparturePoint: estimateAirportTransport(seed.id + "-dep", seed.neighbourhood),
    toPlaces,
  };
}

export const HOTELS: Hotel[] = HOTEL_SEEDS.map(buildHotel);
export const ROOMS: Room[] = HOTEL_SEEDS.flatMap(buildRooms);
export const REVIEWS: ReviewSummary[] = HOTEL_SEEDS.map(buildReview);
export const NEEDS_VERIFICATION: Record<string, string[]> = Object.fromEntries(
  HOTEL_SEEDS.filter((s) => s.needsVerification?.length).map((s) => [s.id, s.needsVerification!])
);

export function hotelsByNeighbourhood(neighbourhood: string): Hotel[] {
  return HOTELS.filter((h) => h.neighbourhood === neighbourhood);
}

export function roomsForHotel(hotelId: string): Room[] {
  return ROOMS.filter((r) => r.hotelId === hotelId);
}

export function reviewForHotel(hotelId: string): ReviewSummary {
  const r = REVIEWS.find((x) => x.hotelId === hotelId);
  if (!r) throw new Error(`No review summary for hotel ${hotelId}`);
  return r;
}
